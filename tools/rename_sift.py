#!/usr/bin/env python3
"""One-time migration of the PalantirMC tree to the Sift Launcher names.

**This is a record as much as a tool.** It was written for the single commit that
renamed the product and its five crates, and it stays in the tree afterwards on
purpose: `docs/RENAME.md` is the inventory of what the old name touched, and this
file is the executable half of it -- the exact substitutions, in the exact order,
with the reason each one is not a plain `str.replace` of the product name. A
later reader asking "what did the rename actually change?" can read both, and a
`--dry-run` against any checkout this has never been applied to prints the same
list it printed the first time.

It is not a general-purpose rebranding tool and it is not expected to be run
twice on the same tree: the second run finds nothing, which is also how it is
tested for idempotency.

Three things it deliberately does **not** do:

* **It does not touch `Cargo.lock`.** The lock file is derived data. Renaming a
  package in it by hand produces a lock that `cargo` disagrees with, and the
  first `cargo build`/`cargo test` rewrites it anyway. Rename the manifests, then
  let cargo regenerate the lock.
* **It does not rename directories.** Git records a rename as a delete plus an
  add unless it is told otherwise, and a script that moves directories before the
  commit is staged leaves `git status` unreadable. The five `git mv` commands are
  printed instead, for a human to run in the order given.
* **It does not add the "read the old name once" fallbacks** that the R1 slice in
  `docs/PLAN-SIFT.md` asks for around the environment variables. Those are code
  changes -- a second `var_os` call and a preference between two answers -- not
  string substitutions, and a substitution pretending to be one would silently
  drop the fallback.

Usage
-----
    python tools/rename_sift.py                 # dry run (the default)
    python tools/rename_sift.py --apply         # rewrite the files
    python tools/rename_sift.py --groups 1      # only the eleven crate pairs
    python tools/rename_sift.py --verbose       # per-rule counts per file

Exit status is 0 for both modes; this tool reports, it does not gate.
"""

from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass
from pathlib import Path

#: The checkout this file lives in, found from its own location so the tool works
#: from any working directory -- including the one `cargo` or CI happens to use.
REPO_ROOT = Path(__file__).resolve().parent.parent

#: Directories never descended into. `vendor/` is a verbatim copy of somebody
#: else's tree (see `.gitattributes`); the rest are build output, captures, or
#: git's own storage.
EXCLUDED_DIRS = (".git", "target", "dist", ".scratch", "vendor")

#: Files never rewritten, with the reason they are special:
#:   Cargo.lock          -- regenerated by cargo, never hand-edited
#:   NOTES.md            -- the project's history; old names are the record
#:   docs/PLAN-SIFT.md   -- the plan that names the *target* spellings
#:   docs/RENAME.md      -- the inventory; it quotes every old string by design
#:   tools/rename_sift.py-- this file; it contains every pattern it searches for
EXCLUDED_FILES = (
    "Cargo.lock",
    "NOTES.md",
    "docs/PLAN-SIFT.md",
    "docs/RENAME.md",
    "tools/rename_sift.py",
)

#: Files where a bare `PalantirMC` is *prose a user reads* rather than an
#: identifier, and therefore becomes "Sift Launcher" (with the space) instead of
#: "SiftLauncher". Everything outside this set gets the identifier spelling, which
#: is what repository names, artifact names and executable names need.
#:
#: Two files are conspicuously absent, both for the same reason -- their literal is
#: a *path*, not a name:
#:
#: * `crates/palantir-core/src/paths.rs` holds `DATA_DIR_NAME`, and
#:   `%APPDATA%\SiftLauncher` is what `docs/PLAN-SIFT.md` R1 decided on. A folder
#:   with a space in it is a folder somebody has to quote.
#: * `installer/sift.nsi` holds the same folder as `${DATA_DIR}`, which has to
#:   agree with it byte for byte. Its display name already comes from
#:   `${PRODUCT}`, which is "Sift Launcher" and needs no substitution.
VISIBLE_FILES = frozenset(
    {
        "LICENSE",
        "README.md",
        "THIRD_PARTY_NOTICES.md",
        "crates/palantir-core/Cargo.toml",
        "crates/palantir-core/src/lib.rs",
        "crates/palantir-core/src/launch.rs",
        "crates/palantir-core/tests/compat.rs",
        "crates/palantir-desktop/Cargo.toml",
        "crates/palantir-desktop/build.rs",
        "crates/palantir-desktop/src/brand.rs",
        "crates/palantir-desktop/src/main.rs",
        "crates/palantir-desktop/src/single.rs",
        "crates/palantir-desktop/src/shell.rs",
        "crates/palantir-desktop/src/theme.rs",
        "crates/palantir-desktop/src/update.rs",
        "crates/palantir-egui/src/main.rs",
        "crates/palantir-loader/src/lib.rs",
        "crates/palantir-net/Cargo.toml",
        "crates/palantir-net/src/lib.rs",
    }
)

#: The five directories the crate rename implies, as (old, new). Printed as
#: `git mv` commands; never executed here.
DIRECTORY_RENAMES = (
    ("crates/palantir-core", "crates/sift-core"),
    ("crates/palantir-net", "crates/sift-net"),
    ("crates/palantir-loader", "crates/sift-loader"),
    ("crates/palantir-desktop", "crates/sift-desktop"),
    ("crates/palantir-egui", "crates/sift-ui"),
)


@dataclass(frozen=True)
class Rule:
    """One substitution, applied to every file it is allowed to touch.

    `scope` exists because the product name has two correct spellings: the display
    name ("Sift Launcher", with the space) in prose, and the identifier spelling
    ("SiftLauncher") in repository, artifact and executable names. A single
    `str.replace` cannot make that choice, so the choice is written down here as
    two rules that cannot both match the same file.
    """

    group: str
    pattern: str
    replacement: str
    reason: str
    scope: str = "any"  # "any" | "visible" | "hidden"


#: Ordered: every pattern is applied to the text the previous one produced, so a
#: more specific rule must come before the general one it would otherwise be
#: eaten by. `PalantirMCSkinBoundary` before `PalantirMC`; `palantirmc` before
#: `palantir`, or `palantirmc-desktop.json` would become `siftmc-desktop.json`.
RULES: tuple[Rule, ...] = (
    # ---- 1. the eleven crate-name pairs, exactly as the brief listed them -----
    Rule("1-crates", "palantir_core", "sift_core", "crate palantir-core -> sift-core (path segment)"),
    Rule("1-crates", "palantir_net", "sift_net", "crate palantir-net -> sift-net (path segment)"),
    Rule("1-crates", "palantir_loader", "sift_loader", "crate palantir-loader -> sift-loader (path segment)"),
    Rule("1-crates", "palantir_desktop", "sift_desktop", "crate palantir-desktop -> sift-desktop (path segment)"),
    Rule("1-crates", "palantir_egui", "sift_ui", "crate palantir-egui -> sift-ui; NOT palantir_egui -> sift_egui"),
    Rule("1-crates", "palantir-core", "sift-core", "package, workspace member and path dependency"),
    Rule("1-crates", "palantir-net", "sift-net", "package, workspace member and path dependency"),
    Rule("1-crates", "palantir-loader", "sift-loader", "package, workspace member and path dependency"),
    Rule("1-crates", "palantir-desktop", "sift-desktop", "package, workspace member and path dependency"),
    Rule("1-crates", "palantir-egui", "sift-ui", "package and directory; NOT palantir-egui -> sift-egui"),
    # ---- 2. forms of the old name that are identifiers, not prose -------------
    Rule(
        "2-identifier-forms",
        "PalantirMCSkinBoundary",
        "SiftSkinBoundary",
        "multipart boundary in an upload body; a space would make it an illegal header value",
    ),
    Rule(
        "2-identifier-forms",
        "PalantirMC.exe",
        "SiftLauncher.exe",
        "executable name: artifact, installer payload, updater target",
    ),
    Rule(
        "2-identifier-forms",
        "PalantirMC/",
        "SiftLauncher/",
        "HTTP User-Agent token; a space would split it into two tokens",
    ),
    Rule(
        "2-identifier-forms",
        'name = "PalantirMC"',
        'name = "SiftLauncher"',
        "Cargo [[bin]] target; cargo target names are path-shaped, not display names",
    ),
    Rule(
        "2-identifier-forms",
        "PalantirEgui",
        "SiftUi",
        "the egui slice's [[bin]] target, following its crate to sift-ui",
    ),
    Rule(
        "2-identifier-forms",
        "PalantirPaths",
        "SiftPaths",
        "the path helper type every module names; `Palantir` does not survive as a type prefix",
    ),
    # ---- 3. the product name itself -----------------------------------------
    Rule("3-product-name", "PalantirMC", "Sift Launcher", "display name in prose the user reads", scope="visible"),
    Rule("3-product-name", "PalantirMC", "SiftLauncher", "identifier spelling everywhere else", scope="hidden"),
    # ---- 4. lower-case paths, files and environment variables ----------------
    Rule("4-paths-and-env", "PALANTIRMC_", "SIFT_", "environment variable prefix (SIFT_HOME, SIFT_FRAME_LOG, ...)"),
    Rule("4-paths-and-env", "palantirmc", "sift", "preferences file, lock file, artifact and temp-directory names"),
    Rule("4-paths-and-env", "palantir", "sift", "anything left in lower case, e.g. `.palantir-test-data/` and `palantir.pid`"),
)

#: Group names in the order they run, for `--groups` and the summary.
GROUPS = tuple(dict.fromkeys(rule.group for rule in RULES))


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="rename_sift.py",
        description="Rename PalantirMC to Sift Launcher in place (dry run by default).",
        epilog="Cargo.lock and directory names are never touched; see docs/RENAME.md.",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--apply",
        action="store_true",
        help="write the replacements (default is a dry run that writes nothing)",
    )
    mode.add_argument(
        "--dry-run",
        action="store_true",
        help="print what would change and write nothing (the default)",
    )
    parser.add_argument(
        "--groups",
        default=",".join(GROUPS),
        help="comma-separated rule groups to run (default: all); names: " + ", ".join(GROUPS),
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="print a per-rule breakdown under each file",
    )
    parser.add_argument(
        "--exclude-glob",
        default="",
        help=(
            "comma-separated fnmatch patterns of paths to leave alone, e.g. "
            "'*.md,docs/*'. The historical ledgers (GATES.md, NOTES.md) record what "
            "was measured under the old name, so a code pass excludes them and a "
            "separate prose pass decides, file by file, what a reader should see."
        ),
    )
    return parser.parse_args(argv)


def selected_rules(spec: str) -> tuple[Rule, ...]:
    """The rules named by `spec`, in their declared order.

    Order comes from `RULES`, not from the order the groups were typed in: the
    substitutions depend on each other, so "run group 4 before group 1" is not a
    thing the operator is allowed to ask for by accident.
    """
    wanted = {name.strip() for name in spec.split(",") if name.strip()}
    unknown = wanted - set(GROUPS)
    if unknown:
        raise SystemExit(f"unknown group(s): {', '.join(sorted(unknown))}\nknown: {', '.join(GROUPS)}")
    return tuple(rule for rule in RULES if rule.group in wanted)


def iter_files() -> tuple[list[Path], list[tuple[str, str]]]:
    """Every candidate file, plus the (path, reason) of the ones excluded by name."""
    files: list[Path] = []
    skipped: list[tuple[str, str]] = []
    for dirpath, dirnames, filenames in os.walk(REPO_ROOT):
        dirnames[:] = sorted(name for name in dirnames if name not in EXCLUDED_DIRS)
        for filename in sorted(filenames):
            path = Path(dirpath) / filename
            relative = path.relative_to(REPO_ROOT).as_posix()
            if relative in EXCLUDED_FILES:
                skipped.append((relative, "excluded by name"))
                continue
            files.append(path)
    return files, skipped


def read_text(path: Path) -> str | None:
    """The file's text, or `None` when it is not UTF-8 text.

    Read and written as bytes so a file's line endings, byte-order mark and
    trailing newline survive the rewrite untouched: this tool changes words, not
    encodings.
    """
    raw = path.read_bytes()
    if b"\x00" in raw:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def scope_allows(rule: Rule, relative: str) -> bool:
    visible = relative in VISIBLE_FILES
    if rule.scope == "visible":
        return visible
    if rule.scope == "hidden":
        return not visible
    return True


def apply_rules(text: str, relative: str, rules: tuple[Rule, ...]) -> tuple[str, list[tuple[Rule, int]]]:
    """Run `rules` over `text`; return the result and what each rule replaced."""
    hits: list[tuple[Rule, int]] = []
    for rule in rules:
        if not scope_allows(rule, relative):
            continue
        count = text.count(rule.pattern)
        if not count:
            continue
        text = text.replace(rule.pattern, rule.replacement)
        hits.append((rule, count))
    return text, hits


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    rules = selected_rules(args.groups)
    applying = bool(args.apply)

    files, skipped_by_name = iter_files()
    patterns = [p.strip() for p in args.exclude_glob.split(",") if p.strip()]
    if patterns:
        import fnmatch

        def excluded(path: object) -> bool:
            relative = str(path).replace("\\", "/")
            return any(fnmatch.fnmatch(relative, pattern) for pattern in patterns)

        kept = [path for path in files if not excluded(path)]
        print(f"excluded by glob: {len(files) - len(kept)} files ({args.exclude_glob})")
        files = kept
    changed: list[tuple[str, int, list[tuple[Rule, int]]]] = []
    skipped_unchanged = 0
    skipped_binary = 0
    unreadable: list[tuple[str, str]] = []

    for path in files:
        relative = path.relative_to(REPO_ROOT).as_posix()
        try:
            text = read_text(path)
        except OSError as error:
            unreadable.append((relative, str(error)))
            continue
        if text is None:
            skipped_binary += 1
            continue
        new_text, hits = apply_rules(text, relative, rules)
        if not hits:
            skipped_unchanged += 1
            continue
        total = sum(count for _, count in hits)
        changed.append((relative, total, hits))
        if applying:
            try:
                path.write_bytes(new_text.encode("utf-8"))
            except OSError as error:
                unreadable.append((relative, str(error)))

    total_occurrences = sum(total for _, total, _ in changed)
    header = "rename_sift: APPLIED" if applying else "rename_sift: dry run (nothing written)"
    print(header)
    print(f"repository: {REPO_ROOT}")
    print(f"groups:     {', '.join(dict.fromkeys(rule.group for rule in rules))}")
    print()

    if changed:
        verb = "rewrote" if applying else "would rewrite"
        print(f"{verb} {len(changed)} files, {total_occurrences:,} occurrences:")
        width = max(len(name) for name, _, _ in changed)
        for relative, total, hits in changed:
            print(f"  {relative.ljust(width)}  {total:5d}")
            if args.verbose:
                for rule, count in hits:
                    print(f"      {count:5d}  {rule.group}: {rule.pattern!r} -> {rule.replacement!r}")
    else:
        print("nothing to change: no old name found in any scanned file.")

    print()
    by_group: dict[str, int] = {}
    by_pattern: dict[str, int] = {}
    for _, _, hits in changed:
        for rule, count in hits:
            by_group[rule.group] = by_group.get(rule.group, 0) + count
            by_pattern[rule.pattern] = by_pattern.get(rule.pattern, 0) + count
    if by_group:
        print("by group:")
        for group in GROUPS:
            if group in by_group:
                print(f"  {group:<18} {by_group[group]:6,d}")
        print()

    print("summary")
    print(f"  files scanned           {len(files):6,d}")
    print(f"  files {'rewritten' if applying else 'to rewrite':<19}{len(changed):6,d}")
    print(f"  occurrences replaced    {total_occurrences:6,d}")
    print(f"  skipped: no old name    {skipped_unchanged:6,d}")
    print(f"  skipped: not UTF-8 text {skipped_binary:6,d}")
    print(f"  skipped: excluded name  {len(skipped_by_name):6,d}  ({', '.join(name for name, _ in skipped_by_name)})")
    if unreadable:
        print(f"  FAILED to read/write    {len(unreadable):6,d}")
        for relative, error in unreadable:
            print(f"      {relative}: {error}")
    print()

    print("directories to rename -- run these yourself, in this order, with `git mv`:")
    old_width = max(len(old) for old, _ in DIRECTORY_RENAMES)
    for old, new in DIRECTORY_RENAMES:
        print(f"  git mv {old.ljust(old_width)}  {new}")
    print()

    print("notes")
    print("  Cargo.lock is not edited: cargo regenerates it from the renamed manifests.")
    print("  The manifests name the new crate paths, so run the git mv commands above")
    print("  before the next cargo build.")
    if not applying:
        print("  Nothing was written. Re-run with --apply to perform these changes.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
